'use strict';
/* Printable Lab Report. Data loads with the owner's session cookie; nothing is embedded in
   the page. Status labels come from the server (code comparison), never from a model. */
(() => {
  const root = document.querySelector('[data-lab-report]'); if (!root) return;
  const LOC = () => window.LC_I18N?.locale() || 'en-GB';   // dates follow the page language (static/js/i18n.js)
  const id = root.dataset.labReport;
  const make = (tag, text, cls) => { const e = document.createElement(tag); if (text != null) e.textContent = text; if (cls) e.className = cls; return e; };
  const STATUS = { within: ['Within printed range', 'ok'], high: ['Above printed range', 'warn'], low: ['Below printed range', 'warn'], unknown: ['No range to compare', 'neutral'] };
  const longDate = s => s ? new Date(s + 'T00:00:00').toLocaleDateString(LOC(), { day: 'numeric', month: 'long', year: 'numeric' }) : 'Collection date not entered';
  function fail(message) {
    const box = make('div', null, 'state-box'); box.setAttribute('role', 'alert');
    const row = make('div', null, 'row'), back = make('a', 'My reports', 'btn primary'); back.href = '/app?view=reports'; row.append(back);
    box.append(make('h1', 'This Lab Report cannot be shown', 'h3'), make('p', message, 'small muted'), row); root.replaceChildren(box);
  }
  function render(r) {
    document.title = r.label + ' · Lab Report | LabClear';
    const head = make('header', null, 'lab-head');
    const title = make('div'); title.append(make('p', 'Lab Report', 'eyebrow'), make('h1', r.label), make('p', longDate(r.date), 'muted'));
    const actions = make('div', null, 'row no-print');
    const print = make('button', 'Print or save as PDF', 'btn primary'); print.type = 'button'; print.onclick = () => window.print();
    const ask = make('a', 'Ask about this report', 'btn'); ask.href = '/app?view=reports';
    actions.append(print, ask); head.append(title, actions);
    const summary = make('div', null, 'lab-summary');
    [['within', 'Within range'], ['high', 'Above range'], ['low', 'Below range'], ['unknown', 'No printed range']].forEach(([k, label]) => {
      const s = make('div', null, 'lab-stat'); s.append(make('strong', String(r.counts[k] || 0), 'num'), make('span', label, 'small muted')); summary.append(s);
    });
    const wrap = make('div', null, 'table-wrap'), t = make('table', null, 'data lab-table'), hr = make('tr');
    const short = d => /^\d{4}-\d{2}-\d{2}$/.test(d || '') ? new Date(d + 'T00:00:00').toLocaleDateString(LOC(), { day: 'numeric', month: 'short', year: 'numeric' }) : d;
    const cols = ['Test', 'Result', 'Unit', 'Printed range', 'Status'].concat(r.previous ? ['Previous, ' + short(r.previous.date), 'Change'] : []);
    cols.forEach((c, i) => { const th = make('th', c, i === 1 || i >= 5 ? 'n' : ''); th.scope = 'col'; hr.append(th); });
    const thead = make('thead'); thead.append(hr); t.append(thead);
    const body = make('tbody');
    r.rows.forEach(x => {
      const tr = make('tr', null, x.status === 'high' || x.status === 'low' ? 'flagged' : ''), st = make('td'), [label, tone] = STATUS[x.status] || STATUS.unknown;
      st.append(make('span', label, 'badge ' + tone));
      const th = make('th', x.name); th.setAttribute('translate', 'no');   // test name as read from the report
      tr.append(th, make('td', x.value, 'n num'), make('td', x.unit || 'None', x.unit ? '' : 'muted'), make('td', x.reference || 'Not printed', x.reference ? 'num' : 'muted'), st);
      tr.firstChild.scope = 'row';
      if (r.previous) {
        const p = x.previous;
        tr.append(make('td', p ? p.value : 'Not in previous', p ? 'n num' : 'n muted'), make('td', !p ? '' : p.change !== null && p.change !== undefined ? (p.change > 0 ? '+' : '') + p.change : 'Not numeric', p && p.change !== null && p.change !== undefined ? 'n num' : 'n muted'));
      }
      body.append(tr);
    });
    t.append(body); wrap.append(t);
    const notes = make('section', null, 'lab-notes small');
    notes.append(make('p', r.note));
    if (!r.trends) { const up = make('p', null, 'no-print'); up.append(document.createTextNode('Change since your previous report is part of LabClear Plus. '), Object.assign(make('a', 'See Plus'), { href: '/app?view=plan' })); notes.append(up); }
    notes.append(make('p', 'Generated by LabClear on ' + new Date(r.generated_at * 1000).toLocaleString(LOC()) + '. Coursework simulation; not a medical document.', 'muted tiny'));
    root.replaceChildren(head, summary, wrap, notes);
  }
  (async () => {
    try { await RS.session(); render(await RS.call('/reports/' + encodeURIComponent(id) + '/lab-report')); }
    catch (e) { fail(e.status === 404 ? 'It does not exist or belongs to another account. Sign in with the account that added it.' : e.message); }
  })();
})();
